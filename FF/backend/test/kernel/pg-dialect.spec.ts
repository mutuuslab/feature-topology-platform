// SQLite → PostgreSQL 방언 번역(D-RD-3 이전 1단계, 20-92 §4.3) — PG 없이 도는 순수 시험.
// 실제 PG에서 같은 SQL이 도는지는 pg-adapter.spec·npm run test:pg가 본다.
import { describe, expect, it } from 'vitest';
import { MIGRATIONS } from '../../src/kernel/migrations';
import { dialectContextOf, splitStatements, translate, translateMigration } from '../../src/kernel/pg-dialect';

const ctx = dialectContextOf(MIGRATIONS);
const q = (sql: string) => translate(sql, ctx).text;

describe('PG 방언 번역 — 질의', () => {
  it('자리표시자 ?는 $n으로, 문자열 안의 ?는 그대로', () => {
    expect(q("SELECT doc FROM feature_version WHERE feature_id = ? AND doc <> '?' AND version = ?")).toBe("SELECT doc FROM feature_version WHERE feature_id = $1 AND doc <> '?' AND version = $2");
  });

  it("INSERT OR IGNORE → ON CONFLICT DO NOTHING, INSERT는 정수 키(없으면 rowid)를 돌려준다", () => {
    const t = translate('INSERT OR IGNORE INTO notification_read (notification_id, user_id, at) VALUES (?, ?, ?)', ctx);
    expect(t.text).toBe('INSERT INTO notification_read (notification_id, user_id, at) VALUES ($1, $2, $3) ON CONFLICT DO NOTHING RETURNING rowid');
    expect(t.returnsId).toBe(true);
    expect(q('INSERT INTO events (id, type) VALUES (?, ?)')).toBe('INSERT INTO events (id, type) VALUES ($1, $2) RETURNING seq');
    expect(q('INSERT INTO audit (at) VALUES (?)')).toBe('INSERT INTO audit (at) VALUES ($1) RETURNING id');
  });

  it('json_extract → jsonb #>> 경로, LIKE → ILIKE, 섞인 대소문자 별칭은 따옴표', () => {
    expect(q("SELECT json_extract(doc, '$.featureId') AS featureId FROM vehicle_request WHERE vin LIKE ?")).toBe(`SELECT ((doc)::jsonb #>> '{featureId}') AS "featureId" FROM vehicle_request WHERE vin ILIKE $1`);
    expect(q("SELECT 1 FROM t WHERE x NOT LIKE 'EN-%'")).toBe("SELECT 1 FROM t WHERE x NOT ILIKE 'EN-%'");
    expect(q('SELECT max(CAST(substr(policy_id, 5) AS INTEGER)) AS m FROM policy')).toBe('SELECT max(CAST(substr(policy_id, 5) AS BIGINT)) AS m FROM policy');
  });

  it('rowid — 정수 키가 있는 표는 그 열, 없는 표는 덧붙인 rowid 열', () => {
    expect(q('SELECT rowid AS rowid FROM security_event ORDER BY rowid')).toBe('SELECT id AS rowid FROM security_event ORDER BY id');
    expect(q('SELECT * FROM vehicle_delivery ORDER BY queued_at, rowid')).toBe('SELECT * FROM vehicle_delivery ORDER BY queued_at, rowid');
  });

  it('PRAGMA는 실행하지 않는다, BEGIN IMMEDIATE는 BEGIN', () => {
    expect(translate('PRAGMA wal_checkpoint(TRUNCATE)', ctx).noop).toBe(true);
    expect(q('BEGIN IMMEDIATE')).toBe('BEGIN');
  });
});

describe('PG 방언 번역 — 마이그레이션', () => {
  it('정수 키 AUTOINCREMENT → IDENTITY, 정수 키 없는 표에는 rowid 열, INTEGER → BIGINT', () => {
    const t = translateMigration({ sql: 'CREATE TABLE a (id INTEGER PRIMARY KEY AUTOINCREMENT, n INTEGER);\nCREATE TABLE b (k TEXT PRIMARY KEY, v REAL, d BLOB);' }, ctx);
    expect(t).toContain('id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, n BIGINT)');
    expect(t).toContain('d BYTEA,\n  rowid BIGINT GENERATED ALWAYS AS IDENTITY)');
    expect(t).toContain('v DOUBLE PRECISION');
  });

  it('추가 전용 트리거(RAISE ABORT) → plpgsql 함수 + 행 트리거, WHEN 조건(하위 질의 포함)은 함수 안으로', () => {
    const t = translateMigration({ sql: "CREATE TRIGGER x_no_delete BEFORE DELETE ON x WHEN (SELECT active FROM g WHERE id = 1) = 0 BEGIN SELECT RAISE(ABORT, 'x는 추가만 가능'); END;" }, ctx);
    expect(t).toContain("CREATE OR REPLACE FUNCTION ff_trg_x_no_delete() RETURNS trigger LANGUAGE plpgsql AS $ff$ BEGIN IF ((SELECT active FROM g WHERE id = 1) = 0) THEN RAISE EXCEPTION '%', 'x는 추가만 가능'; END IF; RETURN OLD; END $ff$;");
    expect(t).toContain('CREATE TRIGGER x_no_delete BEFORE DELETE ON x FOR EACH ROW EXECUTE FUNCTION ff_trg_x_no_delete();');
  });

  it('DROP TRIGGER는 표 이름을 붙인다(마이그레이션에서 찾은 표)', () => {
    expect(translateMigration({ sql: 'DROP TRIGGER status_report_no_delete;' }, ctx)).toBe('DROP TRIGGER status_report_no_delete ON status_report;');
  });

  it('트리거 BEGIN…END 안의 ;로 문을 나누지 않는다', () => {
    expect(splitStatements("CREATE TABLE t (a TEXT); CREATE TRIGGER k BEFORE DELETE ON t BEGIN SELECT RAISE(ABORT, 'a;b'); END; CREATE INDEX i ON t(a);")).toHaveLength(3);
  });

  it('지금 있는 모든 마이그레이션이 번역된다(번역이 못 하는 것은 pg 덮어쓰기)', () => {
    for (const m of MIGRATIONS) expect(() => translateMigration(m, ctx), m.name).not.toThrow();
    const all = MIGRATIONS.map((m) => translateMigration(m, ctx)).join('\n');
    expect(all).not.toMatch(/\bAUTOINCREMENT\b|RAISE\s*\(\s*ABORT|\bINSERT OR IGNORE\b|json_extract/i);
  });

  it('번역 문맥은 표의 정수 키와 트리거의 표를 안다', () => {
    expect(ctx.intKey.get('audit')).toBe('id');
    expect(ctx.intKey.get('feature_version')).toBeUndefined();
    expect(ctx.triggerTable.get('audit_no_delete')).toBe('audit');
  });
});
