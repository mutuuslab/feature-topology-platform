// "표준 따라하기" 시나리오 표 — 보고서 v1.1 18장 케이스 시나리오를 실제 화면에서 따라 하며 규칙·근거 조항이 어디서 어떻게 동작하는지 본다.
// 화면(가이드 패널·스포트라이트)이 이 표를 쓴다. 단계는 실제 라우트와 화면의 data-tour 앵커를 가리킨다(시험이 존재를 검사한다).
// 조작 단계의 완료 판정(check)은 화면 상태(요소·글자)로 한다 — 실서버와 정적 데모(브라우저 시뮬레이터)에서 같은 판정이 돈다.
// 판정은 이 시나리오가 다루는 대상에 묶는다(예: 차단 서랍의 Feature·차량·상태 속성) — 시드의 다른 기록을 열어 통과하지 않게. 남은 상태로 미리 맞을 수 있는 단계는 write로 이 단계의 쓰기를 요구한다.
// 단계가 가리키는 예시 데이터 ID(refs, 경로·문구 속 ID)는 시드에 있어야 한다(backend/test/ext/tutorial-refs.spec.ts). 앞 단계가 만드는 ID는 creates에 적는다.
export type TutorialTrack = 'VIRTUAL' | 'DESIGN' | 'KILL' | 'MARKET' | 'SECURITY' | 'OPERATE';
/** 보고서 1.7 읽기 경로 */
export type ReadingPath = 'BASIS' | 'DESIGN' | 'BUILD' | 'VERIFY_OPERATE';
/** observe = 화면을 보고 이해 · act = 실제로 조작 · fail = 일부러 규칙을 어겨 거부를 확인 */
export type StepKind = 'observe' | 'act' | 'fail';

/** 단계 완료 판정 — 화면 상태로 본다 */
export interface StepCheck {
  /** 결과가 나타나는 화면 요소(CSS 선택자) */
  selector: string;
  /** 요소 글자에 들어 있어야 할 문구(정규식 원문) — 없으면 요소가 있기만 하면 완료 */
  text?: string;
  /** 판정할 화면 경로(정규식 원문) — 없으면 단계 화면. 조작 뒤 다른 화면으로 옮겨 가는 단계(새 Version 등)에 쓴다 */
  path?: string;
  /** 완료 때 보이는 한 줄 */
  doneKo: string;
  /**
   * 이 단계에서 성공해야 하는 쓰기(API 이름, contracts ROUTES) — 하나라도 성공해야 완료.
   * 다른 시나리오·이전 실행이 남긴 상태(실행 기록·차단 기록)로 화면 판정이 미리 맞아도 통과하지 않게 한다.
   * 시드 Version의 분류 초안 저장처럼 다시 할 때 같은 값을 다시 저장할 수 없는 단계에는 쓰지 않는다 — 막히지 않게.
   * 이 시나리오가 새로 만든 Version의 저장(CLASSIFY-GATE 램프 4000)은 처음 저장이라 쓴다
   */
  write?: string[];
}

export interface TutorialStep {
  id: string;
  kind: StepKind;
  title: string;
  /** 지금 할 일 — 누를 버튼·넣을 값까지 */
  doKo: string;
  /** 왜 — 이 단계가 보여 주는 안전 논리 */
  whyKo: string;
  /** 이 단계를 맡는 화면 역할(데모 계정 키, contracts DEMO_PERSONAS) — 다르면 역할 전환 배너 */
  role: string;
  /** 실제 화면 경로 */
  route: string;
  /** 단계 화면 경로 패턴(정규식) — 화면이 다른 경로로 옮겨 가는 단계만(예: 대체된 정책 → 배포 중 판). 없으면 route의 경로·질의 그대로 */
  screen?: string;
  /** 스포트라이트 대상 data-tour 값 */
  anchor: string;
  /** 강조 대상의 이름 — "어디서"에 보인다 */
  targetKo: string;
  /** 보고서 규칙 ID — 근거 조항은 규칙의 '근거' 필드에서 */
  rules: string[];
  /** 보고서 시험 카탈로그 ID(있으면) */
  tests?: string[];
  /** 확인할 결과 */
  expectKo: string;
  /** 완료 판정 — 조작(act·fail) 단계는 화면 결과로 판정한다 */
  check?: StepCheck;
  /** 이 단계가 가리키는 예시 데이터 ID(Feature는 FEAT-00022@1.0.0) — 시드에 있어야 한다 */
  refs?: string[];
  /** 이 단계가 만드는 ID — 뒤 단계가 가리켜도 된다 */
  creates?: string[];
}

